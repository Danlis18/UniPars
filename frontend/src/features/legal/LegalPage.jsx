function useLegalConfig() {
  return useQuery({ queryKey: ["config"], queryFn: () => api("/config"), staleTime: 300_000 });
}

const uah = (kop) => `${(kop / 100).toLocaleString("uk-UA", { maximumFractionDigits: 2 })} ₴`;

// Реквізити продавця — з налаштувань сервера (LEGAL_*). Поки їх немає, справжня оплата вимкнена.
export function Requisites({ legal }) {
  if (!legal?.ready) {
    return <p className="text-muted">Реквізити продавця буде опубліковано тут до початку приймання оплат.</p>;
  }
  return (
    <dl className="grid sm:grid-cols-[180px_1fr] gap-x-4 gap-y-1">
      <dt className="text-muted">Продавець</dt><dd>{legal.name}</dd>
      {legal.tax_id && <><dt className="text-muted">Код (РНОКПП / ЄДРПОУ)</dt><dd>{legal.tax_id}</dd></>}
      {legal.address && <><dt className="text-muted">Адреса</dt><dd>{legal.address}</dd></>}
      {legal.iban && <><dt className="text-muted">IBAN</dt><dd className="break-all">{legal.iban}</dd></>}
      {legal.phone && <><dt className="text-muted">Телефон</dt><dd>{legal.phone}</dd></>}
      <dt className="text-muted">Email</dt><dd><a className="text-primary hover:underline" href={`mailto:${legal.email}`}>{legal.email}</a></dd>
    </dl>
  );
}

